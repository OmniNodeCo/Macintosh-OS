def parse(art):
    rows = [r for r in art.split('\n') if r.strip('\n') != '']
    rows = [r.rstrip('\n') for r in rows]
    if rows and rows[-1] == '':
        rows = rows[:-1]
    # trim blank trailing rows but keep the baseline grid intact
    while rows and not rows[-1].strip('.'):
        rows.pop()
    return rows


def glyph_contours(rows):
    """Turn pixel rows into a list of rectangles (x0, y0, x1, y1) in font units."""
    rects = []
    for r, row in enumerate(rows):
        c = 0
        while c < len(row):
            if row[c] == '#':
                start = c
                while c < len(row) and row[c] == '#':
                    c += 1
                x0, x1 = start * PX, c * PX
                top = (CAP - r) * PX
                bottom = (CAP - r - 1) * PX
                rects.append((x0, bottom, x1, top))
            else:
                c += 1
    return rects


def build_glyph(rows):
    pen = TTGlyphPen(None)
    for (x0, y0, x1, y1) in glyph_contours(rows):
        pen.moveTo((x0, y0))
        pen.lineTo((x1, y0))
        pen.lineTo((x1, y1))
        pen.lineTo((x0, y1))
        pen.closePath()
    return pen.glyph()


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    specials = {'\u2019': 'quotright', '\u201c': 'quotedblleft',
                '\u201d': 'quotedblright', '•': 'bullet',
                '\u2318': 'command', '\u2713': 'checkmark',
                '\uf8ff': 'applelogo'}
    order = ['.notdef'] + [chr(c) for c in range(32, 127)] + list(specials.values())
    cmap = {}
    for c in range(32, 127):
        cmap[c] = chr(c)
    for ch, nm in specials.items():
        cmap[ord(ch)] = nm
    name_of = {chr(c): chr(c) for c in range(32, 127)}
    name_of.update({nm: ch for ch, nm in specials.items()})

    fb = FontBuilder(768, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap(cmap)

    glyphs, metrics = {}, {}
    for name in order:
        if name == '.notdef':
            rows = ['###', '#.#', '#.#', '#.#', '###', '...', '###']
            adv = 6
        else:
            ch = name_of[name]
            rows = parse(A[ch])
            adv = W.get(ch)
            if adv is None:
                adv = max(len(r) for r in rows) + 1
            else:
                adv += 1
        glyphs[name] = build_glyph(rows)
        metrics[name] = (adv * PX, 0)

    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=10 * PX, descent=-DESC * PX, lineGap=0)
    fb.setupNameTable({
        'familyName': 'MacPixel Chicago',
        'styleName': 'Regular',
        'uniqueFontIdentifier': 'MacPixel Chicago; 1.0; Macintosh-OS web clone',
        'fullName': 'MacPixel Chicago Regular',
        'version': 'Version 1.0',
        'psName': 'MacPixelChicago-Regular',
        'licenseDescription': (
            'Original glyphs drawn for the Macintosh-OS web clone. '
            'Released under the MIT License. Not an Apple font; not affiliated '
            'with Apple Inc.'
        ),
    })
    fb.setupOS2(sTypoAscender=10 * PX, sTypoDescender=-DESC * PX, sTypoLineGap=0,
                usWinAscent=10 * PX, usWinDescent=DESC * PX,
                sxHeight=6 * PX, sCapHeight=CAP * PX)
    fb.setupPost()

    out = os.path.join(root, 'assets', 'fonts')
    os.makedirs(out, exist_ok=True)
    ttf = os.path.join(out, 'MacPixelChicago.ttf')
    fb.save(ttf)
    fb.font.flavor = 'woff2'
    fb.save(os.path.join(out, 'MacPixelChicago.woff2'))
    print('wrote', ttf, 'and woff2')


if __name__ == '__main__':
    main()
